<script>
  
document.addEventListener("DOMContentLoaded", function () {

  const pickers = document.querySelectorAll(".picker");
  const mixLines = document.querySelector("#byo-lines");
  const totalElement = document.querySelector("#byo-total");
  const addButton = document.querySelector("#byo-add");
  const afterElement = document.querySelector("#byo-after");

  if (!mixLines || !totalElement) return;

  const currencySymbol = "£";

  // ----------------------------------
  // GET SERVICE DETAILS
  // ----------------------------------

  function getService(picker) {
    const id = picker.dataset.id;
    const name = picker.querySelector(".copy h3")?.textContent.trim() || id;

    const tierButton = picker.querySelector(".tier button[aria-checked='true']");
    const termButton = picker.querySelector(".term button[aria-checked='true']");

    const tier = tierButton?.dataset.value || "bronze";
    const term = termButton?.dataset.value || "1";

    const amountElement = picker.querySelector(".summary .amt");
    const price = parseFloat(amountElement?.dataset.gbp) || 0;

    const isOnePrice = !picker.querySelector(".term");

    return {
      id,
      name,
      tier,
      term: isOnePrice ? null : term,
      price,
      isOnePrice
    };
  }

  // ----------------------------------
  // FORMAT PRICE
  // ----------------------------------

  function formatPrice(amount) {
    return currencySymbol + amount.toLocaleString("en-GB", {
      maximumFractionDigits: 2
    });
  }

  // ----------------------------------
  // UPDATE MIX ROW
  // ----------------------------------

  function updateMixLine(picker) {
    const service = getService(picker);

    let line = mixLines.querySelector(
      '.line[data-id="' + service.id + '"]'
    );

    if (!picker.classList.contains("on")) {
      if (line) line.remove();
      return;
    }

    if (!line) {
      line = document.createElement("div");
      line.className = "line";
      line.dataset.id = service.id;

      line.innerHTML = `
        <div class="copy">
          <b></b>
          <small></small>
        </div>
        <span class="amt"></span>
      `;

      mixLines.appendChild(line);
    }

    const tierName =
      service.tier.charAt(0).toUpperCase() + service.tier.slice(1);

    const termText = service.isOnePrice
      ? "one price"
      : service.term + (service.term === "1" ? " month" : " months");

    line.querySelector(".copy b").textContent = service.name;
    line.querySelector(".copy small").textContent =
      tierName + ", " + termText;

    const amount = line.querySelector(".amt");
    amount.dataset.gbp = service.price;
    amount.dataset.shownCur = "GBP";
    amount.textContent = formatPrice(service.price);
  }

  // ----------------------------------
  // CALCULATE TOTAL
  // ----------------------------------

  function updateTotal() {
    let total = 0;

    mixLines.querySelectorAll(".line").forEach(function (line) {
      const amount = line.querySelector(".amt");

      if (amount) {
        total += parseFloat(amount.dataset.gbp) || 0;
      }
    });

    totalElement.dataset.gbp = total;
    totalElement.dataset.shownCur = "GBP";
    totalElement.textContent = formatPrice(total);

    if (addButton) {
      const hasServices = mixLines.querySelectorAll(".line").length > 0;

      addButton.disabled = !hasServices;
      addButton.setAttribute("aria-disabled", String(!hasServices));
    }

    return total;
  }

  // ----------------------------------
  // UPDATE TIER / TERM SELECTORS
  // ----------------------------------


function updateSegment(segment, selectedButton) {

  segment.querySelectorAll("button").forEach(function (button) {
    const selected = button === selectedButton;

    button.setAttribute("aria-checked", selected ? "true" : "false");
    button.setAttribute("tabindex", selected ? "0" : "-1");
  });

  const indicator = segment.querySelector(".seg-ind");
  if (!indicator) return;

  const mobile = window.matchMedia("(max-width: 767px)").matches;

  const segmentRect = segment.getBoundingClientRect();
  const buttonRect = selectedButton.getBoundingClientRect();

  const x = buttonRect.left - segmentRect.left;

  if (mobile) {
    const top = parseFloat(getComputedStyle(indicator).top) || 0;
    const y = buttonRect.top - segmentRect.top - top;

    indicator.style.width = buttonRect.width + "px";
    indicator.style.height = buttonRect.height + "px";
    indicator.style.transform = `translate(${x}px, ${y}px)`;

  } else {
    indicator.style.width = buttonRect.width + "px";
    indicator.style.height = "";
    indicator.style.transform = `translate(${x}px, 0px)`;
  }
}





  // ----------------------------------
  // SERVICE ON / OFF
  // ----------------------------------

  pickers.forEach(function (picker) {

    const toggle = picker.querySelector(".sw");
    if (!toggle) return;

    toggle.addEventListener("click", function () {

      const isOn = !picker.classList.contains("on");

      picker.classList.toggle("on", isOn);

      toggle.setAttribute("aria-checked", String(isOn));

      updateMixLine(picker);
      updateTotal();

    });

  });

  // ----------------------------------
  // TIER AND TERM CLICK
  // ----------------------------------

  pickers.forEach(function (picker) {

    picker.querySelectorAll(".seg").forEach(function (segment) {

      segment.querySelectorAll("button[data-value]").forEach(function (button) {

        button.addEventListener("click", function () {

          updateSegment(segment, button);

          // Refresh selected service in Your Mix
          updateMixLine(picker);
          updateTotal();

        });

      });

    });

  });

  // ----------------------------------
  // INITIALIZE EXISTING SERVICES
  // ----------------------------------

  pickers.forEach(function (picker) {

    const toggle = picker.querySelector(".sw");
    const isOn = picker.classList.contains("on");

    if (toggle) {
      toggle.setAttribute("aria-checked", String(isOn));
    }

    picker.querySelectorAll(".seg").forEach(function (segment) {
      const selected = segment.querySelector(
        "button[aria-checked='true']"
      );

      if (selected) {
        updateSegment(segment, selected);
      }
    });

    updateMixLine(picker);

  });

  updateTotal();

  // ----------------------------------
  // ADD TO CART
  // ----------------------------------

  if (addButton) {

    addButton.addEventListener("click", function () {

      const selectedServices = [];

      pickers.forEach(function (picker) {

        if (!picker.classList.contains("on")) return;

        const service = getService(picker);

        selectedServices.push({
          id: service.id,
          name: service.name,
          tier: service.tier,
          term: service.term,
          priceGBP: service.price
        });

      });

      if (!selectedServices.length) return;

      const cartData = {
        currency: "GBP",
        services: selectedServices,
        total: selectedServices.reduce(function (sum, service) {
          return sum + service.priceGBP;
        }, 0),
        updatedAt: new Date().toISOString()
      };

      try {
        localStorage.setItem("byoCart", JSON.stringify(cartData));

        // Allow other cart scripts to receive the selected services
        window.dispatchEvent(
          new CustomEvent("byo:add-to-cart", {
            detail: cartData
          })
        );

        addButton.classList.add("added");

        const buttonText = addButton.querySelector("span");

        if (buttonText) {
          buttonText.textContent = "Added to cart";
        }

        if (afterElement) {
          afterElement.classList.add("added");
        }

      } catch (error) {
        console.error("Unable to save cart:", error);
      }

    });

  }

});

